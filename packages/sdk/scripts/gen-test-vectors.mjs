// Generates WebAuthn-shaped P-256 test vectors for the Noir circuit and the SDK tests.
// Signatures come from WebCrypto (the same ECDSA-P256-SHA256 a platform authenticator produces);
// nullifiers come from bb.js Poseidon2, which must match the circuit's Poseidon2::hash.
import { webcrypto, createHash, randomBytes } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Barretenberg } from "@aztec/bb.js";

const here = dirname(fileURLToPath(import.meta.url));
const circuitVectors = resolve(here, "../../../circuits/webauthn/src/test_vectors.nr");
const sdkFixture = resolve(here, "../test/fixtures/webauthn-vector.json");

const P256_N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551n;
const NULLIFIER_DOMAIN = 0x564552414b45595f4e554c4c49464945525f5631n; // "VERAKEY_NULLIFIER_V1"
const APP_ID = 0x7061796e6f77n; // "paynow"
const ORIGIN = "http://localhost:5173";
const RP_ID = "localhost";

const sha256 = b => createHash("sha256").update(b).digest();
const hex = b => "0x" + Buffer.from(b).toString("hex");
const toBig = b => BigInt(hex(b));
const word = v => Buffer.from(v.toString(16).padStart(64, "0"), "hex");
const limbs = b => [toBig(b.subarray(0, 16)), toBig(b.subarray(16, 32))];

const subtle = webcrypto.subtle;
const key = await subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign"]);
const raw = Buffer.from(await subtle.exportKey("raw", key.publicKey));
const x = raw.subarray(1, 33);
const y = raw.subarray(33, 65);

// Synced-passkey flags: UP | UV | BE | BS, signCount 0 (iCloud Keychain / Google Password Manager style).
const rpIdHash = sha256(Buffer.from(RP_ID));
const authData = Buffer.concat([rpIdHash, Buffer.from([0x1d]), Buffer.alloc(4)]);
const actionHash = randomBytes(32);
const clientDataJSON = Buffer.from(
  `{"type":"webauthn.get","challenge":"${actionHash.toString("base64url")}","origin":"${ORIGIN}","crossOrigin":false}`
);
const clientDataHash = sha256(clientDataJSON);
const prfSecret = randomBytes(32);

const rawSig = Buffer.from(
  await subtle.sign({ name: "ECDSA", hash: "SHA-256" }, key.privateKey, Buffer.concat([authData, clientDataHash]))
);
const r = rawSig.subarray(0, 32);
let s = toBig(rawSig.subarray(32));
const lowS = s > P256_N / 2n ? P256_N - s : s;
const highS = P256_N - lowS;
const sigLow = Buffer.concat([r, word(lowS)]);
const sigHigh = Buffer.concat([r, word(highS)]);

const api = await Barretenberg.new({ threads: 1 });
const nullifierOf = async (appId, prf) => {
  const [xh, xl] = limbs(x);
  const [yh, yl] = limbs(y);
  const [sh, sl] = limbs(prf);
  const { hash } = await api.poseidon2Hash({
    inputs: [NULLIFIER_DOMAIN, xh, xl, yh, yl, sh, sl, appId].map(word),
  });
  return toBig(Buffer.from(hash));
};
const nullifier = await nullifierOf(APP_ID, prfSecret);
const nullifierOtherApp = await nullifierOf(APP_ID + 1n, prfSecret);
await api.destroy();

const arr = b => `[${[...b].join(", ")}]`;
const f = v => "0x" + v.toString(16);
const [cdhHi, cdhLo] = limbs(clientDataHash);
const [rpHi, rpLo] = limbs(rpIdHash);
const [prfHi, prfLo] = limbs(prfSecret);

const nr = `// GENERATED by packages/sdk/scripts/gen-test-vectors.mjs — do not edit by hand.
// A WebAuthn-shaped ES256 assertion (synced-passkey flags 0x1d) with a random PRF secret.
pub global PUB_KEY_X: [u8; 32] = ${arr(x)};
pub global PUB_KEY_Y: [u8; 32] = ${arr(y)};
pub global SIGNATURE_LOW_S: [u8; 64] = ${arr(sigLow)};
pub global SIGNATURE_HIGH_S: [u8; 64] = ${arr(sigHigh)};
pub global AUTHENTICATOR_DATA: [u8; 37] = ${arr(authData)};
pub global PRF_SECRET_HI: Field = ${f(prfHi)};
pub global PRF_SECRET_LO: Field = ${f(prfLo)};
pub global CLIENT_DATA_HASH_HI: Field = ${f(cdhHi)};
pub global CLIENT_DATA_HASH_LO: Field = ${f(cdhLo)};
pub global RP_ID_HASH_HI: Field = ${f(rpHi)};
pub global RP_ID_HASH_LO: Field = ${f(rpLo)};
pub global APP_ID: Field = ${f(APP_ID)};
pub global NULLIFIER: Field = ${f(nullifier)};
pub global NULLIFIER_OTHER_APP: Field = ${f(nullifierOtherApp)};
`;
writeFileSync(circuitVectors, nr);
// The consent-to-link circuit tests use the same assertion.
writeFileSync(resolve(here, "../../../circuits/link/src/test_vectors.nr"), nr);

mkdirSync(dirname(sdkFixture), { recursive: true });
writeFileSync(
  sdkFixture,
  JSON.stringify(
    {
      rpId: RP_ID,
      origin: ORIGIN,
      appId: f(APP_ID),
      publicKey: { x: hex(x), y: hex(y) },
      signatureLowS: hex(sigLow),
      signatureHighS: hex(sigHigh),
      authenticatorData: hex(authData),
      clientDataJSON: hex(clientDataJSON),
      actionHash: hex(actionHash),
      prfSecret: hex(prfSecret),
      nullifier: hex(word(nullifier)),
      nullifierOtherApp: hex(word(nullifierOtherApp)),
    },
    null,
    2
  ) + "\n"
);
console.log(`wrote ${circuitVectors}\nwrote ${sdkFixture}`);
